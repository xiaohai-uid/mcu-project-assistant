"""Firmware generator: deterministic skeleton + LLM business logic.

Principles:
- include, library dependency, global objects, pin constants, setup init
  are generated by deterministic adapters (from ComponentDefinition.firmware)
- LLM is ONLY responsible for loop() business rules
- LLM cannot re-select hardware pins
- Output is a complete sketch artifact
"""

from __future__ import annotations

from mcu_worker.domain.components.models import ComponentDefinition
from mcu_worker.domain.models.pin_allocation import PinAllocation
from mcu_worker.domain.platforms.models import PlatformDefinition


class FirmwareGenerator:
    """Generates a complete Arduino sketch from validated design artifacts."""

    def __init__(
        self,
        platform: PlatformDefinition,
        components: list[tuple[str, ComponentDefinition]],
        pin_allocation: PinAllocation,
    ) -> None:
        self._platform = platform
        self._components = components
        self._pins = pin_allocation

    def generate_includes(self) -> list[str]:
        """Generate #include lines from component firmware specs."""
        includes: set[str] = set()
        for _, comp in self._components:
            for inc in comp.firmware.includes:
                includes.add(inc)
        return sorted(includes)

    def generate_constants(self) -> list[str]:
        """Generate pin constant definitions from PinAllocation."""
        lines: list[str] = []
        for assignment in self._pins.assignments:
            pin = assignment.physical_pin
            var_name = f"PIN_{assignment.instance_id.upper()}_{assignment.signal.upper()}"
            # Convert pin name to Arduino constant
            if pin.startswith("A"):
                lines.append(f"const int {var_name} = {pin};")
            elif pin.startswith("D"):
                pin_num = pin[1:]
                lines.append(f"const int {var_name} = {pin_num};")
            else:
                lines.append(f"const int {var_name} = {pin};")
        return lines

    def generate_globals(self) -> list[str]:
        """Generate global object declarations (e.g. DHT dht(PIN, DHT22))."""
        lines: list[str] = []
        seen_vars: dict[str, int] = {}
        for instance_id, comp in self._components:
            adapter = comp.firmware.codegen_adapter
            base_var = comp.firmware.var_name.lower()
            # Ensure unique variable names for multiple instances
            count = seen_vars.get(base_var, 0)
            seen_vars[base_var] = count + 1
            var = base_var if count == 0 else f"{base_var}_{count + 1}"

            if adapter == "dht":
                # Find the pin for this instance
                pin = self._get_first_pin(instance_id)
                pin_num = pin[1:] if pin and pin.startswith("D") else "2"
                dht_type = "DHT22" if "22" in comp.id else "DHT11"
                lines.append(f"DHT {var}({pin_num}, {dht_type});")
            elif adapter == "lcd":
                lines.append(f"LiquidCrystal_I2C {var}(0x27, 16, 2);")
            elif adapter == "oled":
                lines.append(f"Adafruit_SSD1306 {var}(128, 64, &Wire, -1);")
            elif adapter == "servo":
                lines.append(f"Servo {var};")
            elif adapter == "neopixel":
                pin = self._get_first_pin(instance_id)
                pin_num = pin[1:] if pin and pin.startswith("D") else "6"
                lines.append(f"Adafruit_NeoPixel {var}(16, {pin_num}, NEO_GRB + NEO_KHZ800);")
            # generic adapters don't need global objects

        return lines

    def generate_setup(self) -> list[str]:
        """Generate setup() body with initialization calls."""
        lines: list[str] = ["Serial.begin(9600);"]
        seen_vars: dict[str, int] = {}
        for instance_id, comp in self._components:
            adapter = comp.firmware.codegen_adapter
            base_var = comp.firmware.var_name.lower()
            count = seen_vars.get(base_var, 0)
            seen_vars[base_var] = count + 1
            var = base_var if count == 0 else f"{base_var}_{count + 1}"

            if adapter == "dht":
                lines.append(f"{var}.begin();")
            elif adapter == "lcd":
                lines.append(f"{var}.init();")
                lines.append(f"{var}.backlight();")
            elif adapter == "oled":
                lines.append(f"{var}.begin(SSD1306_SWITCHCAPVCC, 0x3C);")
                lines.append(f"{var}.clearDisplay();")
            elif adapter == "servo":
                pin = self._get_first_pin(instance_id)
                pin_num = pin[1:] if pin and pin.startswith("D") else "9"
                lines.append(f"{var}.attach({pin_num});")
            elif adapter == "neopixel":
                lines.append(f"{var}.begin();")

        return lines

    def generate_sketch(self, business_logic: str | None = None) -> str:
        """Generate the complete .ino sketch."""
        parts: list[str] = []

        # Includes
        for inc in self.generate_includes():
            parts.append(f"#include <{inc}>")
        if self.generate_includes():
            parts.append("")

        # Constants
        constants = self.generate_constants()
        if constants:
            parts.extend(constants)
            parts.append("")

        # Globals
        globals_ = self.generate_globals()
        if globals_:
            parts.extend(globals_)
            parts.append("")

        # setup()
        parts.append("void setup() {")
        for line in self.generate_setup():
            parts.append(f"  {line}")
        parts.append("}")
        parts.append("")

        # loop()
        parts.append("void loop() {")
        if business_logic:
            for line in business_logic.strip().split("\n"):
                parts.append(f"  {line}")
        else:
            parts.append("  // TODO: Add business logic")
            parts.append("  delay(1000);")
        parts.append("}")
        parts.append("")

        return "\n".join(parts)

    def _get_first_pin(self, instance_id: str) -> str | None:
        """Get the first assigned pin for an instance."""
        for a in self._pins.assignments:
            if a.instance_id == instance_id:
                return a.physical_pin
        return None
